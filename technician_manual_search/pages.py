def nice_text(raw):
    return re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", html.escape(raw), flags=re.DOTALL)


def highlight(text, terms):
    out, last = [], 0
    for match in re.finditer(r"[A-Za-z0-9]+", text):
        out.append(e(text[last:match.start()]))
        word = match.group(0)
        out.append(f"<mark>{e(word)}</mark>" if search.stem(word.lower()) in terms else e(word))
        last = match.end()
    out.append(e(text[last:]))
    return "".join(out)


def snippet(section, terms, length=260):
    paragraphs = [" ".join(p.split()) for p in re.split(r"\n\s*\n", section["text"]) if p.strip()]
    paragraphs = [p for p in paragraphs if not p.lower().startswith("notes")] or paragraphs
    if not paragraphs:
        return ""
    best = max(paragraphs, key=lambda p: sum(1 for w in re.findall(r"[a-z0-9]+", p.lower()) if search.stem(w) in terms))
    if len(best) > length:
        best = best[:length].rsplit(" ", 1)[0] + "..."
    return highlight(best, set(terms))


