def hit_html(hit, best_score):
    section = hit["section"]
    relevance = max(1, int(round(100 * hit["score"] / best_score)))
    return (f"<article class='hit'><div class='hit-head'><span class='tag'>{e(search.reference(section))}</span>"
            f"<h3><a href='/section?n={section['number']}'>{e(section['title'])}</a></h3>"
            f"<span class='rel'><meter min='0' max='100' value='{relevance}'></meter>{relevance}% match</span></div>"
            f"<p class='snip'>{snippet(section, hit['matched'])}</p>"
            f"<details class='read'><summary>Read the whole section</summary><div class='doc'>{nice_text(section['text'])}</div></details></article>")


def refusal_panel(title, text, extra=""):
    return f"<div class='refusal'><b>{e(title)}</b><p>{e(text)}</p>{extra}</div>"


def manual_results(question, hits, enough, ai_on):
    from ai import MESSAGES
    if not hits:
        return refusal_panel("No section matches", MESSAGES["no_match"],
                             "<p>Try different words, or use the AI guidance option. It is not taken from the manual.</p>")
    best = hits[0]["score"]
    top = hits[0]["section"]
    kind = art.kind_for_section(top["number"])
    ports = art.ports_mentioned(kind, top["text"])
    cards = "".join(hit_html(hit, best) for hit in hits)
    if not enough:
        return (refusal_panel("No supported answer", MESSAGES["no_match"],
                              "<p>The closest sections are listed below. You can also try the AI guidance option. It is not taken from the manual.</p>")
                + "<h2>Closest sections</h2>" + cards)
    if not ai_on:
        return (f"<p class='muted'>{e(MESSAGES['ai_off'])}</p><div class='answer-grid'><div>{cards}</div>{guide_block(kind, ports)}</div>")
    return (f"<section class='answer' id='answer-box' data-mode='manual' data-q='{e(question)}' aria-live='polite'>"
            f"<h2>Answer from the manual</h2><div class='answer-grid'><div class='answer-body'>{art.loader('manual')}</div>"
            f"{guide_block(kind, ports)}</div></section><h2>Best matching sections</h2>{cards}")


def ai_results(question, ai_on):
    if not ai_on:
        from ai import MESSAGES
        return refusal_panel("AI is switched off", MESSAGES["ai_off"], "<p>An administrator can add a Gemini key in the settings.</p>")
    link = f"/search?mode=manual&q={urllib.parse.quote(question)}"
    return ("<div class='notice-ai'><b>Generated by AI, not from the manual.</b> This is general guidance from the AI's own knowledge. "
            "Check it against the manual and your supervisor before acting.</div>"
            f"<section class='answer general' id='answer-box' data-mode='ai' data-q='{e(question)}' aria-live='polite'>"
            f"<h2>AI guidance</h2><div class='answer-grid'><div class='answer-body'>{art.loader('ai')}</div>{waiting_guide()}</div></section>"
            f"<p><a href='{e(link)}'>Check the same question in the manual</a></p>")


def search_page(profile, question, mode, hits, enough, ai_on):
    body = f"<h1>Ask a question</h1>{search_form(question, mode)}"
    if not question:
        tries = "".join(f"<a href='/search?mode=manual&q={urllib.parse.quote(x)}'>{e(x)}</a>" for x in EXAMPLES)
        body += f"<div class='empty'><b>Choose an option and ask a question.</b><p class='muted'>Try one of these.</p><div class='try'>{tries}</div></div>"
    elif mode == "ai":
        body += ai_results(question, ai_on)
    else:
        body += manual_results(question, hits, enough, ai_on)
    return shell("Ask", body, profile, "search")


