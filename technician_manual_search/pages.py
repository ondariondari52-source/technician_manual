def section_page(profile, sections, number):
    position = next((i for i, s in enumerate(sections) if s["number"] == number), None)
    if position is None:
        return shell("Not found", "<h1>Section not found</h1><p><a href='/manual'>Back to the manual</a></p>", profile, "manual")
    section = sections[position]
    previous = (f"<a class='btn btn-ghost' href='/section?n={sections[position - 1]['number']}'>Previous: Section {sections[position - 1]['number']}</a>"
                if position > 0 else "<span></span>")
    following = (f"<a class='btn btn-ghost' href='/section?n={sections[position + 1]['number']}'>Next: Section {sections[position + 1]['number']}</a>"
                 if position + 1 < len(sections) else "<span></span>")
